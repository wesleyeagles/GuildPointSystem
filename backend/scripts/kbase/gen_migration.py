"""Generate the Flyway migration that applies kbase (FORCE&STEEL) data to the guild inventory.

Usage: python -I gen_migration.py <kbase-all.json> <out.sql>
"""
import json
import re
import sys

def q(s):
    return "'" + s.replace("'", "''") + "'"


def effect(a):
    # "Damage avoidance -100.00" -> "Damage avoidance -100"
    return re.sub(r"(-?\d+)\.00\b", r"\1", a)


def fix_name(n):
    # the kbase cuts "[40]" / "[rev.45]" before the closing bracket
    if n.count("[") > n.count("]"):
        n += "]"
    return n


def nums(s):
    return [int(x) for x in re.findall(r"-?\d+", s)]


def main(src, out):
    items = json.load(open(src, encoding="utf-8"))["items"]
    rows = []
    for it in items:
        p = it.get("p", [])
        atk = next((nums(x) for x in p if x.startswith("Attack")), [])
        frc = next((nums(x) for x in p if x.startswith("Force attack")), [])
        dfn = next((nums(x) for x in p if x.startswith("Defence")), [])
        eff = json.dumps([effect(a) for a in it.get("a", [])], ensure_ascii=False)
        rows.append("(" + ", ".join([
            q(it["c"]), q(fix_name(it["n"])), str(it.get("l", 0)),
            str(atk[0] if len(atk) > 0 else "NULL"), str(atk[1] if len(atk) > 1 else "NULL"),
            str(frc[0] if len(frc) > 0 else "NULL"), str(frc[1] if len(frc) > 1 else "NULL"),
            str(dfn[0] if len(dfn) > 0 else "NULL"), str(dfn[1] if len(dfn) > 1 else "NULL"),
            q(eff) + "::jsonb",
        ]) + ")")

    sql = f"""-- Guild inventory with FORCE&STEEL data from the Cerberus kbase (cerberus-games.com/kbase/items, English).
-- Same source as the damage calculator. Matched by game_code; items not in the kbase keep the Lua data.
-- Rarity is not touched: the kbase grade numbers don't match our labels (kbase 4 = Relic, ours 4 = Leon).
-- Generated by gen_migration.py from {len(rows)} kbase items.

CREATE TEMP TABLE _kbase_item (
    game_code   VARCHAR(50) PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    level       INT          NOT NULL,
    attack_min  INT,
    attack_max  INT,
    force_min   INT,
    force_max   INT,
    def_power   INT,
    def_rate    INT,
    effects     JSONB        NOT NULL
);

INSERT INTO _kbase_item VALUES
{",\n".join(rows)};

UPDATE item i
SET name = k.name
FROM _kbase_item k
WHERE i.deleted = FALSE AND LOWER(i.game_code) = k.game_code
  -- the kbase drops apostrophes and quotes; keep our name when that is the only difference
  AND REGEXP_REPLACE(LOWER(i.name), '[''"]', '', 'g') <> LOWER(k.name);

UPDATE item_weapon w
SET level = k.level,
    attack_min = COALESCE(k.attack_min, w.attack_min),
    attack_max = COALESCE(k.attack_max, w.attack_max),
    force_attack_min = COALESCE(k.force_min, w.force_attack_min),
    force_attack_max = COALESCE(k.force_max, w.force_attack_max),
    -- an empty kbase list doesn't erase effects we already have
    special_effects = CASE WHEN k.effects = '[]'::jsonb THEN w.special_effects ELSE k.effects END
FROM item i
JOIN _kbase_item k ON LOWER(i.game_code) = k.game_code
WHERE w.item_id = i.id AND i.deleted = FALSE;

UPDATE item_armor a
SET level = k.level,
    avg_def_power = COALESCE(k.def_power, a.avg_def_power),
    defense_success_rate = COALESCE(k.def_rate, a.defense_success_rate),
    -- an empty kbase list doesn't erase effects we already have
    special_effects = CASE WHEN k.effects = '[]'::jsonb THEN a.special_effects ELSE k.effects END
FROM item i
JOIN _kbase_item k ON LOWER(i.game_code) = k.game_code
WHERE a.item_id = i.id AND i.deleted = FALSE;

UPDATE item_accessory c
SET special_effects = CASE WHEN k.effects = '[]'::jsonb THEN c.special_effects ELSE k.effects END
FROM item i
JOIN _kbase_item k ON LOWER(i.game_code) = k.game_code
WHERE c.item_id = i.id AND i.deleted = FALSE;

UPDATE game_lua_item g
SET name = CASE WHEN REGEXP_REPLACE(LOWER(g.name), '[''"]', '', 'g') = LOWER(k.name) THEN g.name ELSE k.name END,
    level_required = k.level
FROM _kbase_item k
WHERE LOWER(g.game_code) = k.game_code;

DROP TABLE _kbase_item;
"""
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(sql)
    print(f"{len(rows)} rows -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
